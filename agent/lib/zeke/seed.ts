/** An ISO time on the buyer's calendar (Dubai, UTC+4, no daylight saving). `day` 0 is today. */
function dubai(hhmm: string, day = 0) {
  const [h, m] = hhmm.split(":").map(Number);
  const now = new Date(Date.now() + 4 * 3600_000);
  return new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + day, h - 4, m)).toISOString();
}

